async page => {
  await page.context().clearCookies();
  await page.goto('http://127.0.0.1:3000/');
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'Start drawing',exact:true}).click();
  const canvas=page.getByLabel('White drawing wall');
  await canvas.waitFor();
  const b=await canvas.boundingBox();
  await page.mouse.move(b.x+b.width*.25,b.y+b.height*.35);await page.mouse.down();
  await page.mouse.move(b.x+b.width*.5,b.y+b.height*.55,{steps:16});
  await page.mouse.move(b.x+b.width*.65,b.y+b.height*.3,{steps:14});await page.mouse.up();
  const original=await canvas.evaluate(el=>el.toDataURL());
  await page.getByRole('button',{name:'Talk about my drawing',exact:true}).click();
  await page.getByRole('checkbox',{name:/Let the AI look/}).check();
  await page.getByRole('button',{name:'Look at my drawing together'}).click();
  const reply=page.getByRole('textbox',{name:'Your reply',exact:true});
  await reply.fill('The two lines are a kite string. I liked their curve. They are not a plant.');
  await page.getByRole('button',{name:'Send',exact:true}).click();
  await page.getByRole('button',{name:'Make a record',exact:true}).click();
  await page.getByRole('textbox',{name:'Your editable record',exact:true}).fill('I drew a kite string and enjoyed following its curve.');
  await page.getByRole('button',{name:'Confirm my record',exact:true}).click();
  await page.getByRole('button',{name:'Save this drawing',exact:true}).click();
  await page.getByRole('textbox',{name:'Drawing title',exact:true}).fill('Kite string study');
  await page.getByRole('checkbox',{name:/Save this drawing and any reviewed record/}).check();
  await page.getByRole('button',{name:'Save drawing',exact:true}).click();
  await page.getByRole('heading',{name:'Saved to My drawings.'}).waitFor();
  await page.getByRole('button',{name:'Keep drawing',exact:true}).click();
  if(await canvas.evaluate(el=>el.toDataURL())!==original)throw new Error('Returning to drawing changed the pixels');
  await page.getByRole('button',{name:'Open studio choices'}).click();
  await page.getByRole('button',{name:/My drawings Revisit/}).click();
  await page.getByRole('button',{name:/Kite string study/}).click();
  await page.getByRole('button',{name:'Choose professional support'}).click();
  await page.getByRole('button',{name:'Choose a time'}).first().click();
  await page.getByLabel('Date',{exact:true}).fill('2026-11-20');
  await page.getByRole('radio',{name:'10:00',exact:true}).check();
  await page.getByRole('button',{name:'Choose what to share'}).click();
  await page.getByRole('checkbox',{name:'This drawing',exact:true}).check();
  await page.getByRole('checkbox',{name:'My reviewed record',exact:true}).check();
  await page.getByRole('checkbox',{name:/I have checked this preview/}).check();
  await page.getByRole('button',{name:/Confirm demo appointment/}).click();
  await page.getByRole('button',{name:'Withdraw shared items'}).waitFor();
  const shared=await page.request.get('http://127.0.0.1:3000/api/wall?view=professional');
  const packet=await shared.json();
  if(packet.queue.length!==1||!packet.queue[0].image||packet.queue[0].summary!=='I drew a kite string and enjoyed following its curve.')throw new Error('Wrong professional packet');
  if(JSON.stringify(packet).includes('I liked their curve. They are not a plant.'))throw new Error('Raw chat leaked');
  await page.getByRole('button',{name:'Withdraw shared items'}).click();
  await page.getByText('No active background is shared for this drawing.').waitFor();
  const revoked=await (await page.request.get('http://127.0.0.1:3000/api/wall?view=professional')).json();
  if(revoked.queue.length)throw new Error('Withdrawal did not clear professional queue');
  await page.reload();
  const snapshot=await (await page.request.get('http://127.0.0.1:3000/api/wall')).json();
  const work=snapshot.session.works.find(w=>w.title==='Kite string study');
  if(!work||work.status!=='saved'||!work.summary.confirmed||work.conversationConsent)throw new Error('Saved record or separate chat consent was not retained');
  await page.goto('http://127.0.0.1:3000/#gallery');
  await page.getByRole('button',{name:/Kite string study/}).waitFor();
  return {mainFlow:'passed',pixelContinuity:'passed',professionalAllowlist:'passed',withdrawal:'passed',reload:'passed'};
}
